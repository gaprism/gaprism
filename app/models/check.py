"""CheckResult and Finding models for observation persistence and rule interpretation."""

from __future__ import annotations

import uuid
from datetime import datetime
from typing import TYPE_CHECKING, Any

from sqlalchemy import (
    CheckConstraint,
    DateTime,
    ForeignKey,
    String,
    UniqueConstraint,
)
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.models.base import BaseUUIDModel, TimestampMixin

if TYPE_CHECKING:
    from app.models.annotation import FindingAnnotation


class CheckResult(BaseUUIDModel, TimestampMixin):
    """Immutable technical check result outcome."""

    __tablename__ = "check_result"

    workspace_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("workspace.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    assessment_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("assessment.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    run_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("scan_run.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    host_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("host.id", ondelete="CASCADE"),
        nullable=True,
        index=True,
    )
    logical_check_key: Mapped[str] = mapped_column(String(255), nullable=False)
    subject_kind: Mapped[str] = mapped_column(String(32), nullable=False)
    check_type: Mapped[str] = mapped_column(String(64), nullable=False)
    status: Mapped[str] = mapped_column(String(32), nullable=False)
    reason_code: Mapped[str | None] = mapped_column(String(64), nullable=True)
    verdict: Mapped[str | None] = mapped_column(String(64), nullable=True)
    observed_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)
    collected_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)
    adapter_version: Mapped[str | None] = mapped_column(String(64), nullable=True)
    payload: Mapped[dict[str, Any]] = mapped_column(JSONB, nullable=False, default=dict)
    attribution: Mapped[str | None] = mapped_column(String(64), nullable=True)
    confidence: Mapped[str | None] = mapped_column(String(32), nullable=True)

    __table_args__ = (
        UniqueConstraint("run_id", "logical_check_key", name="uq_check_result_run_key"),
        CheckConstraint(
            "status IN ('succeeded', 'failed', 'skipped')",
            name="ck_check_result_status",
        ),
        CheckConstraint(
            "subject_kind IN ('hostname', 'endpoint', 'ip', 'url')",
            name="ck_check_result_subject_kind",
        ),
    )

    def __repr__(self) -> str:
        return f"<CheckResult {self.check_type} {self.status} ({self.id})>"


class Finding(BaseUUIDModel, TimestampMixin):
    """Versioned rule finding generated by technical interpretation."""

    __tablename__ = "finding"

    workspace_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("workspace.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    assessment_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("assessment.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    run_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("scan_run.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    host_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("host.id", ondelete="CASCADE"),
        nullable=True,
        index=True,
    )
    rule_id: Mapped[str] = mapped_column(String(64), nullable=False)
    rule_version: Mapped[str] = mapped_column(String(32), nullable=False)
    subject_key: Mapped[str] = mapped_column(String(255), nullable=False)
    severity: Mapped[str] = mapped_column(String(32), nullable=False)
    confidence: Mapped[str] = mapped_column(String(32), nullable=False)
    attribution: Mapped[str] = mapped_column(String(64), nullable=False)
    message_key: Mapped[str] = mapped_column(String(128), nullable=False)
    message_parameters: Mapped[dict[str, Any]] = mapped_column(JSONB, nullable=False, default=dict)

    annotations: Mapped[list[FindingAnnotation]] = relationship(
        "FindingAnnotation",
        back_populates="finding",
        cascade="all, delete-orphan",
        order_by="FindingAnnotation.created_at",
    )

    __table_args__ = (
        CheckConstraint(
            "severity IN ('informational', 'low', 'medium', 'high', 'critical')",
            name="ck_finding_severity",
        ),
        CheckConstraint(
            "confidence IN ('low', 'medium', 'high', 'unknown')",
            name="ck_finding_confidence",
        ),
        CheckConstraint(
            "attribution IN ('hostname_supported', 'ip_only', 'shared_infrastructure', 'unknown')",
            name="ck_finding_attribution",
        ),
    )

    def __repr__(self) -> str:
        return f"<Finding {self.rule_id} {self.severity} ({self.id})>"
