"""``docs/rules.md``, generated from the rules themselves so that it cannot drift from the code.

Rewrite it with ``uv run python -m app.rules.docs``; ``--check`` only reports whether it is current.
``tests/rules/test_rules_docs.py`` fails when the committed file is out of date.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

from app.rules import RULES, Rule

DOC_PATH = Path(__file__).resolve().parents[2] / "docs" / "rules.md"

SECTIONS = (
    (
        "host",
        "Host rules",
        "Run once per host of the scan, over what that host's checks collected.",
    ),
    (
        "ip",
        "Address rules",
        "Run once per public address a scanner reported on, however many hosts resolve to it; the "
        "finding lists those hosts. Addresses of shared infrastructure (CDN edges, multi-tenant "
        "hosting) are skipped: what is open there says nothing about the vendor.",
    ),
    ("domain", "Domain rules", "Run once per scan, over the checks of the domain itself."),
)

INTRO = """\
# Rules

> Generated from the code by `uv run python -m app.rules.docs`. Change a rule in `app/rules/`
> and regenerate; do not edit this file by hand (a test fails when it is out of date).

A **rule** is a pure function: stored check results in, findings out. It never touches the network
or the database. The checks collect facts; the rules judge them. That keeps judgements testable
with recorded data and lets a rule be refined and re-run over old scans
(`flask findings evaluate`).

## What a finding carries

- **Severity** — how bad it is if true: Critical, High, Medium, Low or Informational. The current
  rules produce High and below; Critical is reserved.
- **Confidence** — how sure we are that it is true: high, medium, low or unknown. It is separate
  from severity: a CDN edge outside the allowed area is a Medium finding with low confidence.
- **Attribution** — whose it is: *confirmed for the hostname*, *seen on the address only*,
  *shared infrastructure* (an address many tenants use) or *the whole domain*. An address is not a
  hostname; findings say which one they rest on.
- **Evidence** — the ids of the check results the decision is based on. A finding points at its
  evidence; it does not copy it.
- **Fingerprint** — `sha256(rule id | subject)`. It does not change with severity, parameters or the
  rule's version, so a decision about a finding (accepting it, S2.6) still applies after a re-scan
  and after the rule is refined.

**No finding is not a clean bill of health.** A check that failed, timed out or found nothing gives
a rule nothing to read, and nothing to read is never a finding. The pages say so next to the
findings, and report which checks did not complete.

## Settings

- `DATA_LOCATION_ALLOWED` — ISO country codes an address may be located in (rule
  `LOCATION_OUTSIDE_EU_CH`). Default: the EU-27, the EEA (IS, LI, NO) and CH.
- `BREACH_RECENT_MONTHS` — a public breach newer than this is High, an older one Medium (rule
  `PUBLIC_BREACH_HISTORY`). Default: 24.

## Adding a rule

One function in `app/rules/host.py`, `ip.py` or `domain.py` with the `@host_rule`, `@ip_rule` or
`@domain_rule` decorator (id, title, one-sentence message with `%(name)s` placeholders, advice, a
description of when it fires, the severities it can produce, the checks it reads and the labels of
its facts). Add a test in `tests/rules/` that feeds it the output of the real check, and regenerate
this file. Wording changes keep the rule's version; a change in *what* it flags raises it.
"""


def _placeholders(text: str) -> str:
    """``%(host)s`` as ``{host}``: readable in a document."""
    return re.sub(r"%\((\w+)\)s", r"{\1}", text)


def _severities(rule: Rule) -> str:
    return " or ".join(severity.capitalize() for severity in reversed(rule.severities))


def _checks(rule: Rule) -> str:
    names = ", ".join(f"`{key}`" for key in rule.checks)
    return f"reads the {names} check" + ("s" if len(rule.checks) > 1 else "")


def _rule(rule: Rule) -> str:
    lines = [
        f"### `{rule.id}`",
        "",
        f"**{rule.title}** · {_severities(rule)} · {_checks(rule)} · version {rule.version}",
        "",
        f"*Fires when:* {rule.trigger}",
        "",
        f"*Says:* {_placeholders(rule.summary)}",
        "",
        f"*Advice:* {rule.advice}",
    ]
    if rule.labels:
        lines += ["", "*Facts shown:* " + ", ".join(rule.labels.values())]
    return "\n".join(lines)


def render() -> str:
    """The whole document."""
    parts = [INTRO]
    rows = ["## Index", "", "| Rule | Severity | Flags |", "|---|---|---|"]
    for scope, _title, _note in SECTIONS:
        rows += [
            f"| [`{rule.id}`](#{rule.id.lower()}) | {_severities(rule)} | {rule.title} |"
            for rule in RULES.values()
            if rule.scope == scope
        ]
    parts.append("\n".join(rows) + "\n")
    for scope, title, note in SECTIONS:
        chosen = [rule for rule in RULES.values() if rule.scope == scope]
        if chosen:
            body = "\n\n".join(_rule(rule) for rule in chosen)
            parts.append(f"## {title}\n\n{note}\n\n{body}\n")
    return "\n".join(parts)


def main(argv: list[str] | None = None) -> int:
    arguments = sys.argv[1:] if argv is None else argv
    text = render()
    current = DOC_PATH.read_text(encoding="utf-8") if DOC_PATH.exists() else ""
    if "--check" in arguments:
        if current != text:
            sys.stderr.write(
                "docs/rules.md is out of date: run `uv run python -m app.rules.docs`\n"
            )
            return 1
        return 0
    DOC_PATH.write_text(text, encoding="utf-8", newline="\n")
    sys.stdout.write(f"wrote {DOC_PATH} ({len(RULES)} rules)\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
